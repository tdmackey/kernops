#!/usr/bin/env bash
# Build an upstream-stable line (e.g. 7.3-lts) natively on Linux: materialise the
# tree from the record, render our packaging, settle the config, build the debs.
#
# Usage: build-line.sh <line> <series> [debian/rules targets...]
#   e.g. build-line.sh 7.3-lts resolute
#        build-line.sh 7.3-lts resolute binary-headers binary-kernops   # no tools
#
# Run it on the Ubuntu series you are building for (a container, VM or WSL
# distro of that series): the toolchain is part of the result.
#
# Environment:
#   RELEASE=1   full profile (debug symbols, ABI and module checks)
#   SBOM=0      skip the bill of materials (stage 5)
#   WORK_ROOT   see scripts/lib/common.sh; must be a case-sensitive filesystem
#
# Deliberately NOT run under fakeroot. The packaging declares
# Rules-Requires-Root: no, and fakeroot funnels every file operation of every
# compiler through one daemon: measured here, it left a 24-core machine 82% idle
# and made the build about five times slower.
set -euo pipefail
# shellcheck source=scripts/lib/common.sh
. "$(cd "$(dirname "$0")/.." && pwd)/scripts/lib/common.sh"

MONO="$(cd "$(dirname "$0")/.." && pwd)"
LINE="${1:?usage: build-line.sh <line> <series> [debian/rules targets...]}"
SERIES="${2:?usage: build-line.sh <line> <series> [debian/rules targets...]}"
shift 2
KPM="$MONO/scripts/kpm"

# One directory per line and series: a build for one series must not delete or
# share the tree of another. A fixed path also keeps ccache hits across runs.
OUT="$WORK_ROOT/build/$LINE/$SERIES"
TREE="$OUT/tree"
ARCH="$(dpkg --print-architecture)"

if [ $# -eq 0 ]; then
    set -- binary-headers "binary-$VENDOR"
    [ "$ARCH" = arm64 ] && set -- "$@" "binary-$VENDOR-64k"
    set -- "$@" binary-perarch          # tools: perf, bpftool, cpupower, Hyper-V daemons, ...
fi
PROFILE=(skipdbg=true skipabi=true skipmodule=true)
[ -n "${RELEASE:-}" ] && PROFILE=()

# In the disposable builder container, use the pahole we built for this series
# (userspace/matrix.tsv) rather than the series' own: BTF is generated by it.
if [ -n "${INSTALL_BUILD_DEPS:-}" ] && ls "$WORK_ROOT/userspace/$SERIES"/pahole_*.deb >/dev/null 2>&1; then
    ( cd "$WORK_ROOT/userspace/$SERIES" && dpkg-scanpackages -m . > Packages 2>/dev/null )
    echo "deb [trusted=yes] file:$WORK_ROOT/userspace/$SERIES ./" > /etc/apt/sources.list.d/local-userspace.list
    apt-get update -qq
    DEBIAN_FRONTEND=noninteractive apt-get install -y -qq --no-install-recommends pahole >/dev/null
fi
echo "pahole: $(pahole --version 2>/dev/null || echo missing)   gcc: $(gcc -dumpfullversion)   rustc: $(rustc --version 2>/dev/null | cut -d' ' -f2 || echo none)"

echo "════ [1/5] reconstruct $LINE from the record"
"$KPM" --line "$LINE" verify --strict
rm -rf "$TREE"
mkdir -p "$OUT"
rm -f "$OUT"/*.deb "$OUT"/*.ddeb "$OUT"/*.buildinfo "$OUT"/*.changes
rm -rf "$OUT/sbom"
"$KPM" --line "$LINE" apply "$TREE"

echo "════ [2/5] render packaging for $SERIES"
"$KPM" --line "$LINE" packaging "$TREE" --series "$SERIES"

cd "$TREE"
# The builder image has the build dependencies of the series' own kernel, not of
# this one. debian/rules does not check, so say what is missing: a tool built
# without an optional library loses a feature silently.
if missing="$(dpkg-checkbuilddeps 2>&1)"; then :; else
    echo "-- build dependencies not installed:${missing#*dependencies:}" | fold -s -w 110
fi
# A clean PATH: on WSL the default one searches Windows directories for every command.
export PATH="/usr/lib/ccache:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
export DEB_BUILD_OPTIONS="parallel=$(nproc)"
export CCACHE_DIR="${CCACHE_DIR:-$WORK_ROOT/ccache}"
# Cache hits must not depend on where the tree lives. For a RELEASE build this
# also means cached objects may carry another directory's debug-info paths.
export CCACHE_BASEDIR="$WORK_ROOT/build" CCACHE_NOHASHDIR=1
# Kconfig prompts must take their defaults; never let them read our stdin.
exec </dev/null

echo "════ [3/5] settle the config for this toolchain"
debian/rules clean >/dev/null
# The first pass records compiler-dependent values and reports them as changes
# (non-zero exit). The second pass must be clean.
debian/rules updateconfigs >"$OUT/updateconfigs.log" 2>&1 || true
if ! debian/rules updateconfigs >>"$OUT/updateconfigs.log" 2>&1; then
    echo "!! config does not settle; see $OUT/updateconfigs.log" >&2
    grep -E 'check-config: CONFIG' "$OUT/updateconfigs.log" | tail -20 >&2
    exit 1
fi

echo "════ [4/5] build: $*"
debian/rules "$@" "${PROFILE[@]}" >"$OUT/build.log" 2>&1 || {
    echo "!! build failed; see $OUT/build.log" >&2
    grep -nE ' error: |\*\*\* ' "$OUT/build.log" | head -20 >&2
    exit 1
}

echo "════ [5/5] record what was built"
# The debs exist at this point. A failure here stops a RELEASE build, which must
# ship its records, and is a warning otherwise.
record_failed() { echo "!! $1" >&2; [ -z "${RELEASE:-}" ] || exit 1; }
VERSION="$(dpkg-parsechangelog -S Version)"
# The build environment: every installed package and its version.
dpkg-genbuildinfo --build=binary -O"$OUT/linux-${VENDOR}_${VERSION}_${ARCH}.buildinfo" 2>"$OUT/buildinfo.log" \
    || record_failed "no .buildinfo written; see $OUT/buildinfo.log"

# A software bill of materials per flavour, from the kernel's own generator
# (scripts/sbom, see Documentation/tools/sbom): the image and every module, the
# source files they were compiled from, and which of our patches reach them.
# SBOM=0 skips it.
SRCARCH="$(sed -nE 's/^build_arch[[:space:]]*=[[:space:]]*//p' "debian.$VENDOR/rules.d/$ARCH.mk")"
IMAGE="$(sed -nE 's/^build_image[[:space:]]*=[[:space:]]*//p' "debian.$VENDOR/rules.d/$ARCH.mk")"
if [ "${SBOM:-1}" != 0 ] && [ -f scripts/sbom/sbom.py ]; then
    [ -n "$SRCARCH" ] && [ -n "$IMAGE" ] || record_failed "cannot read build_arch/build_image from rules.d/$ARCH.mk"
    for obj in debian/build/build-*; do
        [ -f "$obj/modules.order" ] || continue
        flavour="${obj##*/build-}"
        dest="$OUT/sbom/$flavour"
        rm -rf "$dest"; mkdir -p "$dest"
        { echo "arch/$SRCARCH/boot/$IMAGE"; sed 's/\.o$/.ko/' "$obj/modules.order"; } > "$dest/roots.txt"
        if SRCARCH="$SRCARCH" python3 scripts/sbom/sbom.py --src-tree "$TREE" --obj-tree "$TREE/$obj" \
                --roots-file "$dest/roots.txt" --generate-spdx --generate-used-files \
                --output-directory "$dest" --package-version "$VERSION" \
                --build-id "linux-$VENDOR-$VERSION-$ARCH-$flavour" >"$dest/sbom.log" 2>&1; then
            # Every intermediate object and its command line: large, rarely read.
            zstd -q -T0 --rm "$dest/sbom-build.spdx.json" || record_failed "cannot compress $dest/sbom-build.spdx.json"
            echo "── $flavour: $(wc -l < "$dest/sbom.used-files.txt") source files, $(( $(wc -l < "$dest/roots.txt") - 1 )) modules"
            python3 "$MONO/scripts/sbom-patches.py" "$LINE" "$dest/sbom.used-files.txt" -o "$dest/patches.json" \
                || record_failed "cannot match patches to the files built for $flavour"
        else
            record_failed "SBOM generation failed for $flavour; see $dest/sbom.log"
        fi
    done
fi
# A summary for the status page (tools/dashboard).
python3 "$MONO/scripts/write-build-record.py" --out "$OUT" --line "$LINE" --series "$SERIES" --arch "$ARCH" \
    --version "$VERSION" --base "$("$KPM" lines | awk -F'\t' -v l="$LINE" '$1==l{print $2}')" \
    ${RELEASE:+--release} --tool "gcc=$(gcc -dumpfullversion)" \
    --tool "pahole=$(pahole --version 2>/dev/null | sed 's/^v//')" \
    --tool "rustc=$(rustc --version 2>/dev/null | cut -d' ' -f2)" || record_failed "no build record written"
ls -la "$OUT"/*.deb 2>/dev/null || echo "(these targets produce no .deb)"
